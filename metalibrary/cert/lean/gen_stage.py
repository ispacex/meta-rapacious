# -*- coding: utf-8 -*-
"""
Write MetalibCert/Stage_<TAG>.lean: the theorem that the certificates in data/cert_<TAG>/ check
and that the rapacious rule leaves the given numbers of classes.

    python3 gen_stage.py TAG N:HIGH:LOW [N:HIGH:LOW ...]

data/cert_<TAG>/ holds block_*.txt, cell_*.txt and cells.txt (the claim, cert/cells_<TAG>.txt).
"""
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent


def main():
    tag, expect = sys.argv[1], [tuple(map(int, a.split(":"))) for a in sys.argv[2:]]
    d = HERE / "data" / f"cert_{tag}"
    inc = lambda p: f'include_str "../data/cert_{tag}/{p.name}"'
    blocks = sorted(d.glob("block_*.txt"))
    cells = sorted(d.glob("cell_*.txt"))
    cols = ", ".join(str(n) for n, _, _ in expect)
    res = ", ".join(f"({n}, {h}, {l})" for n, h, l in expect)
    text = f"""/- Generated by gen_stage.py: {len(blocks)} rank certificates, {len(cells)} cell certificates. -/
import MetalibCert.Check

namespace MetalibCert.Stage_{tag}

def claim : String := include_str "../data/cert_{tag}/cells.txt"

def blocks : List String := [
  {(","+chr(10)+"  ").join(inc(p) for p in blocks)}]

def cells : List String := [
  {(","+chr(10)+"  ").join(inc(p) for p in cells)}]

/-- The certificates check (exact dimensions of E² in the claimed cells, closure of the claim under
the rule's arrows, the whole columns), and the rapacious rule, with either fill, leaves these
numbers of classes over π_N: (N, high fill, low fill). Evaluated by the compiler (`native_decide`). -/
theorem rule_survivors : checkAll claim blocks cells [{cols}] = some [{res}] := by
  native_decide

end MetalibCert.Stage_{tag}
"""
    out = HERE / "MetalibCert" / f"Stage_{tag}.lean"
    out.write_text(text)
    print("wrote", out)


if __name__ == "__main__":
    main()
